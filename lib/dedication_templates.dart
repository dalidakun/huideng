/// 回向模板：供「功德回向」抽屉里的模板列表使用，点击即填入上方输入框。
class DedicationTemplate {
  /// 模板名称。
  final String title;

  /// 适用场景说明（可为空）。
  final String applicable;

  /// 回向正文。
  final String text;

  const DedicationTemplate(this.title, this.applicable, this.text);
}

/// 回向模板分组：用于抽屉页按组折叠展示。
/// [start] 为组内首个模板下标，[end] 为结束下标（不含）。
class DedicationGroup {
  final String title;
  final int start;
  final int end;

  const DedicationGroup(this.title, this.start, this.end);

  int get count => end - start;

  List<DedicationTemplate> get templates =>
      kDedicationTemplates.sublist(start, end);
}

